function makeElement(tag, className, textValue) {
    var el = document.createElement(tag);
    if (className) { el.className = className; }
    if (textValue !== undefined) { el.appendChild(document.createTextNode(textValue)); }
    return el;
}

function makeIcon(name, kind, large) {
    var box = makeElement('span', 'image-box ' + (large ? 'large-icon' : 'small-icon'));
    var letter = makeElement('span', 'image-fallback', name.substring(0, 1).toUpperCase());
    var img = document.createElement('img');
    img.alt = name;
    img.loading = 'lazy';
    if (kind === 'champion') {
        img.src = GAME_IMAGES + 'champion/' + name + '.png';
    } else if (kind === 'rune' && RUNE_ICONS[name]) {
        img.src = RUNE_IMAGES + RUNE_ICONS[name];
    } else if (kind === 'item' && ITEM_ICONS[name]) {
        img.src = GAME_IMAGES + 'item/' + ITEM_ICONS[name] + '.png';
    } else {
        img.style.display = 'none';
    }
    img.onerror = function () { this.style.display = 'none'; };
    box.appendChild(letter);
    box.appendChild(img);
    return box;
}

function makeItem(name, kind) {
    var tile = makeElement('span', 'build-tile');
    tile.appendChild(makeIcon(name, kind, false));
    tile.appendChild(makeElement('span', 'tile-name', name));
    return tile;
}

function makeSection(title, names, kind) {
    var section = makeElement('div', 'build-section');
    section.appendChild(makeElement('div', 'section-name', title));
    var tiles = makeElement('div', 'tiles');
    var i;
    for (i = 0; i < names.length; i++) {
        tiles.appendChild(makeItem(names[i], kind));
    }
    section.appendChild(tiles);
    return section;
}

function buildGuide(matchup) {
    var panel = makeElement('div', 'guide-panel');
    panel.id = 'guide-' + matchup.picture;
    var title = makeElement('div', 'guide-heading', GUIDE_CHAMPION.toUpperCase() + ' VS ' + matchup.name.toUpperCase());
    panel.appendChild(title);
    var table = makeElement('table', 'guide-table');
    table.cellSpacing = '0';
    var row = table.insertRow(0);
    var left = row.insertCell(0);
    var right = row.insertCell(1);
    left.className = 'guide-runes';
    right.className = 'guide-items';
    left.appendChild(makeSection('01  //  RUNES', matchup.runes, 'rune'));
    right.appendChild(makeSection('02  //  STARTING ITEMS', matchup.start, 'item'));
    right.appendChild(makeSection('03  //  CORE ITEMS', matchup.core, 'item'));
    right.appendChild(makeSection('04  //  BOOTS', matchup.boots, 'item'));
    right.appendChild(makeSection('05  //  OPTIONAL ITEMS', matchup.optional, 'item'));
    panel.appendChild(table);
    return panel;
}

function toggleGuide(matchup, button, wrapper) {
    if (currentlyOpen === matchup.picture) {
        currentlyOpen = '';
    } else {
        currentlyOpen = matchup.picture;
    }
    drawMatchups(lastSearch);
    if (currentlyOpen) {
        var active = document.getElementById('card-' + currentlyOpen);
        if (active) { active.scrollIntoView({ block: 'nearest' }); }
    }
}

function drawMatchups(searchValue) {
    var target = document.getElementById('opponent-list');
    if (!target) { return; }
    lastSearch = searchValue || '';
    var search = lastSearch.toLowerCase();
    target.innerHTML = '';
    var count = 0;
    var i;
    for (i = 0; i < MATCHUPS.length; i++) {
        var matchup = MATCHUPS[i];
        if (matchup.name.toLowerCase().indexOf(search) === -1) { continue; }
        count++;
        var wrapper = makeElement('div', 'champion-card');
        wrapper.id = 'card-' + matchup.picture;
        var button = makeElement('button', 'champion-button');
        button.type = 'button';
        button.setAttribute('aria-expanded', currentlyOpen === matchup.picture ? 'true' : 'false');
        if (currentlyOpen === matchup.picture) { button.className += ' active'; }
        button.appendChild(makeIcon(matchup.picture, 'champion', true));
        button.appendChild(makeElement('span', 'champion-title', matchup.name));
        button.appendChild(makeElement('span', 'expand-text', currentlyOpen === matchup.picture ? '[ - CLOSE GUIDE ]' : '[ + VIEW GUIDE ]'));
        (function(m, b, w) {
            b.onclick = function() { toggleGuide(m, b, w); };
        })(matchup, button, wrapper);
        wrapper.appendChild(button);
        if (currentlyOpen === matchup.picture) {
            wrapper.appendChild(buildGuide(matchup));
        }
        target.appendChild(wrapper);
    }
    var counter = document.getElementById('match-count');
    if (counter) { counter.textContent = count + ' / ' + MATCHUPS.length + ' champions'; }
    if (count === 0) {
        target.appendChild(makeElement('div', 'no-results', 'No champion found. Try another name.'));
    }
}

function initialize() {
    var input = document.getElementById('champion-search');
    if (input) {
        input.oninput = function() {
            currentlyOpen = '';
            drawMatchups(this.value);
        };
        // When someone clicks a featured opponent on the homepage,
        // automatically show that guide on the matchup page.
        var requested = decodeURIComponent(window.location.hash.substring(1)).toLowerCase();
        var i;
        for (i = 0; i < MATCHUPS.length; i++) {
            if (MATCHUPS[i].name.toLowerCase() === requested) {
                currentlyOpen = MATCHUPS[i].picture;
                input.value = MATCHUPS[i].name;
                break;
            }
        }
        drawMatchups(input.value);
    }
    var homeCount = document.getElementById('home-count');
    if (homeCount) { homeCount.textContent = MATCHUPS.length + ' OPPONENT GUIDES'; }
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initialize);
} else {
    initialize();
}
